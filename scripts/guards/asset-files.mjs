import { extname } from 'node:path';
import { collectAllFiles, toRepoPath } from './source-files.mjs';

/**
 * Fence: no image, font or audio file is ever committed (PLAN §2.1, ADR-0002).
 *
 * The repository is code-only. Every pixel, every glyph and every sound is
 * produced by a generator in `art/` or `audio/`, and the artefacts those
 * generators produce are build products: hash-checked, regenerated, gitignored if
 * they are written down at all. A committed `.png` is therefore never a mistake
 * about this file — it is a binary that cannot be reviewed, that drifts from the
 * generator the moment either changes, and that quietly becomes the source of
 * truth the commit made it.
 *
 * The check is on file names rather than on contents on purpose. A guard that
 * looked inside files would have to decide what a PNG's magic bytes mean and
 * would still be blind to an asset renamed `data.bin`; a guard on extensions says
 * what the repository's own rule says — the shape of the file is the offence —
 * and it names every one of them, so the fix is one deletion.
 *
 * What it deliberately does not cover: an asset pasted into a source file as a
 * base64 string, or fetched at runtime. The first is caught in review by the fact
 * that code-only repositories look like code, and the second is caught by the
 * fetch being a dependency rather than a file. Both are said out loud here rather
 * than pretended away.
 */

/** The file kinds the repository may not hold, and what each kind is. */
export const ASSET_EXTENSIONS = new Map([
  // Images.
  ['.png', 'image'],
  ['.jpg', 'image'],
  ['.jpeg', 'image'],
  ['.gif', 'image'],
  ['.webp', 'image'],
  ['.avif', 'image'],
  ['.bmp', 'image'],
  ['.ico', 'image'],
  ['.tga', 'image'],
  ['.tif', 'image'],
  ['.tiff', 'image'],
  ['.svg', 'image'],
  // Fonts.
  ['.ttf', 'font'],
  ['.otf', 'font'],
  ['.woff', 'font'],
  ['.woff2', 'font'],
  ['.eot', 'font'],
  ['.fon', 'font'],
  ['.fnt', 'font'],
  // Audio, and the video a recording would arrive as.
  ['.mp3', 'audio'],
  ['.ogg', 'audio'],
  ['.oga', 'audio'],
  ['.opus', 'audio'],
  ['.wav', 'audio'],
  ['.flac', 'audio'],
  ['.aac', 'audio'],
  ['.m4a', 'audio'],
  ['.mid', 'audio'],
  ['.midi', 'audio'],
  ['.mp4', 'audio'],
  ['.webm', 'audio'],
]);

/** @typedef {import('./violations.mjs').Violation} Violation */

/**
 * Every committed file whose extension names an image, a font or a sound, with
 * the kind it is, so the report says what was added and not merely that
 * something was.
 *
 * @param {string} root Repository root.
 * @returns {Violation[]}
 */
export function findAssetFiles(root) {
  /** @type {Violation[]} */
  const violations = [];

  for (const file of collectAllFiles(root, ['.'])) {
    const kind = ASSET_EXTENSIONS.get(extname(file).toLowerCase());
    if (kind === undefined) continue;

    violations.push({
      file: toRepoPath(root, file),
      line: 1,
      column: 1,
      message: `is a committed ${kind} file — every asset is generated by code (ADR-0002)`,
    });
  }

  return violations;
}
